import { describe, expect, it } from "vitest";

import { DESCRIPTION_LIMIT, prDescription } from "./pr-description.js";

describe("prDescription", () => {
	it("is empty for no description", () => {
		expect(prDescription(null)).toBe("");
		expect(prDescription(undefined)).toBe("");
		expect(prDescription("  \n ")).toBe("");
	});

	it("keeps what the author wrote, with Windows line ends made plain", () => {
		expect(prDescription("## What\r\n\r\nA thing.\r\n")).toBe("## What\n\nA thing.");
	});

	it("drops Sourcery's auto-generated summary to the end", () => {
		const body =
			"Fixes the feed.\n\n<!-- This is an auto-generated description by sourcery-ai. -->\n## Summary by Sourcery\n\n- a\n- b";
		expect(prDescription(body)).toBe("Fixes the feed.");
	});

	it("drops a Sourcery block between its markers and keeps the text after it", () => {
		const body = [
			"Before.",
			"<!-- Generated by sourcery-ai[bot]: start reviewer_guide -->",
			"## Reviewer's Guide",
			"lots of text",
			"<!-- Generated by sourcery-ai[bot]: end reviewer_guide -->",
			"After.",
		].join("\n");
		expect(prDescription(body)).toBe("Before.\n\nAfter.");
	});

	it("drops a heading that names Sourcery with its section only", () => {
		const body =
			"## Why\n\nBecause.\n\n## Summary by Sourcery\n\n- x\n\n### Details\n\nmore\n\n## Testing\n\nRan it.";
		expect(prDescription(body)).toBe("## Why\n\nBecause.\n\n## Testing\n\nRan it.");
	});

	it("drops a command typed to Sourcery", () => {
		expect(prDescription("Does a thing.\n@sourcery-ai summary\n")).toBe("Does a thing.");
	});

	it("drops HTML comments, such as a template's hints", () => {
		expect(prDescription("<!-- describe the change -->\nThe change.\n<!--\nmulti\nline\n-->")).toBe("The change.");
	});

	it("closes up the blank runs the removals leave", () => {
		expect(prDescription("a\n\n\n\n\nb")).toBe("a\n\nb");
	});

	it("cuts a long description with an ellipsis", () => {
		const text = prDescription("x".repeat(DESCRIPTION_LIMIT + 50));
		expect(text).toHaveLength(DESCRIPTION_LIMIT);
		expect(text.endsWith("…")).toBe(true);
	});

	it("leaves a description at the limit alone", () => {
		expect(prDescription("x".repeat(DESCRIPTION_LIMIT))).toHaveLength(DESCRIPTION_LIMIT);
	});
});
