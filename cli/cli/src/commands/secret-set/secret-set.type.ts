import type { Logger } from "@theholocron/observability/core";

import type { LoadedConfig } from "../../config/index.js";
import { PluginLoader, type RuntimeContext, type SecretScope } from "../../plugin/index.js";
import type { RandomBytes } from "../generated-secrets/index.js";
import type { HandOffSecretInput, HandOffSecretResult } from "../secret-handoff/index.js";

export type SecretSetPrint = (line: string) => void;

/** Where `new secret` puts the value: the `secrets` capability (GitHub), or the private import file for a vault. */
export type SecretTarget = "github" | "file";

export interface RunSecretSetInput {
	loaded: LoadedConfig;
	context: RuntimeContext;
	/** Secret name (e.g., `NPM_TOKEN`). */
	name: string;
	/** Secret value. If absent, resolves via stdin / env. */
	value?: string;
	/** Read from stdin instead of positional or env var. */
	fromStdin?: boolean;
	/** Read from a specific env var rather than implicit-by-name. */
	fromEnv?: string;
	/** Defaults to `{ kind: 'repo' }`. */
	scope?: SecretScope;
	/** Where the value goes; defaults to `github`. */
	target?: SecretTarget;
	/** Make the value (only for a name in `GENERATED_SECRETS`) instead of taking one; refused beside a given value. */
	generate?: boolean;
	/**
	 * `file` target: the vault Environment the file is to be imported into, as `--env` was given (a layer word or a
	 * name). With it the import is checked and the hint names it.
	 */
	environment?: string;
	/** `file` target: skip the question. */
	yes?: boolean;
	/** `file` target: asks the question; absent without a terminal, which then needs `yes`. */
	confirm?: (message: string) => Promise<boolean>;
	loader?: PluginLoader;
	print?: SecretSetPrint;
	/** Structured-logging sink — sibling of `print`. Defaults to the command-bound root. */
	logger?: Logger;
	/** Lets tests inject a stdin reader. Defaults to reading process.stdin. */
	readStdin?: () => Promise<string>;
	/** Where generated bytes come from; tests inject a fixed one. */
	random?: RandomBytes;
	/** Resolves `--env` to the vault's Environment name. Defaults to `resolveEnvironmentId`. */
	resolveEnvironment?: (id: string, repoRoot: string) => Promise<string>;
	/** The private-file hand-off; tests inject a fake. Defaults to `handOffSecret`. */
	handOff?: (input: HandOffSecretInput) => Promise<HandOffSecretResult>;
	/** Whether there is a terminal to ask on and to wait for the import on. Defaults to `process.stdin.isTTY`. */
	interactive?: boolean;
}

export interface SecretSetReport {
	status: "ok" | "fail" | "dry-run" | "cancelled";
	name: string;
	/** The `secrets` scope; absent for the `file` target. */
	scope?: SecretScope;
	message?: string;
}
